// One-off: copy the woff2 files we use from node_modules into /assets/fonts and
// write /assets/fonts/fonts.css (latin + latin-ext subsets only).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const out = path.join(root, 'assets', 'fonts');
const sets = [
  ['atkinson-hyperlegible', ['400', '700', '400-italic']],
  ['jetbrains-mono', ['400', '500']],
];
let css = '/* Generated by build/sync-fonts.js. Fonts: OFL-1.1. */\n';
for (const [pkg, weights] of sets) {
  const dir = path.join(root, 'node_modules', '@fontsource', pkg);
  for (const w of weights) {
    for (const subset of ['latin-ext', 'latin']) {
      const src = fs.readFileSync(path.join(dir, `${subset}-${w}.css`), 'utf8');
      const face = src.replace(/src:[^;]+;/, (m) => {
        const file = m.match(/files\/([^)]+\.woff2)/)[1];
        fs.copyFileSync(path.join(dir, 'files', file), path.join(out, file));
        return `src: url(${file}) format('woff2');`;
      }).replace(/font-display: swap;\n\s*/, '');
      css += face + '\n';
    }
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
console.log('fonts synced:', fs.readdirSync(out).length - 1, 'files');
